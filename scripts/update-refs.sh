#!/usr/bin/env bash
# Regenerates lib/: reference-only (signature) assemblies the plugin compiles against, so CI can build
# without the game. Run after a game update or BepInEx upgrade, then rebuild and commit lib/.
# Needs: a game install where BepInEx has run once (BepInEx/interop exists), and
#        dotnet tool install -g JetBrains.Refasmer.CliTool
set -euo pipefail

GAME_DIR="${GAME_DIR:-$HOME/Library/Containers/com.adrianlungu.rum/Bottles/EDE0E85D-87F5-459D-B5AD-C926B0714506/drive_c/Program Files (x86)/Steam/steamapps/common/Heroes of Might and Magic Olden Era}"
REPO_DIR="$(cd "$(dirname "$0")/.." && pwd)"
LIB_DIR="$REPO_DIR/lib"
REFASMER="${REFASMER:-$HOME/.dotnet/tools/refasmer}"

# BepInEx and Il2CppInterop (open source) plus the game's generated interop (signatures only).
CORE=(BepInEx.Core BepInEx.Unity.IL2CPP 0Harmony Il2CppInterop.Runtime Il2CppInterop.Common)
INTEROP=(Hex Hex.Shared Il2Cppmscorlib UnityEngine.CoreModule)

[ -d "$GAME_DIR/BepInEx/interop" ] || { echo "No BepInEx/interop in $GAME_DIR (run the game once with BepInEx)" >&2; exit 1; }

rm -rf "$LIB_DIR"
mkdir -p "$LIB_DIR"

inputs=()
for name in "${CORE[@]}"; do inputs+=("$GAME_DIR/BepInEx/core/$name.dll"); done
for name in "${INTEROP[@]}"; do inputs+=("$GAME_DIR/BepInEx/interop/$name.dll"); done

"$REFASMER" -q -c --omit-non-api-members=true -O "$LIB_DIR" "${inputs[@]}" || true

# Refasmer cannot parse some interop assemblies (UnityEngine.CoreModule: "Read out of bounds");
# those are engine wrappers rather than game code, so they are copied unmodified.
for input in "${inputs[@]}"; do
  [ -f "$LIB_DIR/$(basename "$input")" ] || { echo "copied unstripped: $(basename "$input")"; cp "$input" "$LIB_DIR/"; }
done

{
  echo "Reference assemblies generated by scripts/update-refs.sh on $(date -u +%Y-%m-%d)."
  echo "Game build: $(grep -o 'build-guid=[a-f0-9]*' "$GAME_DIR/HeroesOldenEra_Data/boot.config" || echo unknown)"
  echo "BepInEx: $(head -1 "$GAME_DIR/BepInEx/core/BepInEx.Core.xml" >/dev/null 2>&1 && cat "$GAME_DIR/.doorstop_version" 2>/dev/null || echo unknown)"
} > "$LIB_DIR/README.txt"

du -sh "$LIB_DIR"
ls "$LIB_DIR"
